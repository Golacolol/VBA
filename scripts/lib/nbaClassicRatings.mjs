function defaultOvr(pos, role) {
  if (role === "star") return 90;
  if (role === "starter") return 82;
  return 74;
}

export function peakOvrFor(name, pos = "SF", role = "starter") {
  if (CLASSIC_PEAK_OVR[name] != null) return CLASSIC_PEAK_OVR[name];
  // Fuzzy fallback for partial matches (e.g. accented names).
  const key = Object.keys(CLASSIC_PEAK_OVR).find((k) => name.includes(k) || k.includes(name));
  if (key) return CLASSIC_PEAK_OVR[key];
  return defaultOvr(pos, role);
}

/**
 * Build basketball attrs aimed at an explicit target overall.
 * Shared by classic peaks and current-roster curation.
 * @param {string} pos
 * @param {number} target
 * @param {{ name?: string, jitter?: () => number }} [opts]
 */
export function attrsTowardOvr(pos, target, opts = {}) {
  const name = opts.name ?? "";
  const jitter = opts.jitter ?? (() => 0);
  const shape = POS_SHAPE[pos] ?? POS_SHAPE.SF;
  const bias = PLAYER_BIASES[name] ?? {};
  const j = () => Math.floor(jitter() * 3) - 1;
  const ovr = clamp(target, 40, 99);

  const val = (key, fallbackDelta = 0) => {
    const delta = (shape[key] ?? fallbackDelta) + (bias[key] ?? 0) + j();
    return clamp(ovr + delta, 40, 99);
  };

  const finishing = val("finishing");
  const midRange = val("midRange");
  const threePoint = val("threePoint", -2);
  const freeThrow = val("freeThrow");
  const ballHandle = val("ballHandle");
  const passAccuracy = val("passAccuracy", -1);
  const perimeterD = val("perimeterD");
  const interiorD = val("interiorD", -2);
  const rebound = val("rebound", -2);
  const steal = val("steal", -1);
  const block = val("block", -3);
  const speed = val("speed");
  const vertical = val("vertical");
  const strength = val("strength");
  const stamina = val("stamina", 1);
  const iq = val("iq");
  const clutch = val("clutch");

  return {
    finishing,
    midRange,
    threePoint,
    freeThrow,
    ballHandle,
    passAccuracy,
    perimeterD,
    interiorD,
    rebound,
    steal,
    block,
    speed,
    acceleration: clamp(speed + 2, 40, 99),
    vertical,
    strength,
    stamina,
    iq,
    clutch,
    // Football mirrors (UI / legacy paths)
    pace: speed,
    passing: passAccuracy,
    longPassing: passAccuracy,
    vision: iq,
    control: ballHandle,
    dribbling: ballHandle,
    shooting: finishing,
    shotPower: clamp(finishing + 2, 40, 99),
    longShots: threePoint,
    defending: clamp(Math.round((perimeterD + interiorD) / 2), 40, 99),
    composure: clutch,
    jumping: vertical,
    overall: ovr,
  };
}

/**
 * Build basketball attrs aimed at classic peak OVR for deriveOverall / card display.
 * @param {string} pos
 * @param {string} name
 * @param {{ role?: "star"|"starter"|"bench", jitter?: () => number, targetOvr?: number }} [opts]
 */
export function classicAttrsFor(pos, name, opts = {}) {
  const role = opts.role ?? "starter";
  const target = opts.targetOvr ?? peakOvrFor(name, pos, role);
  return attrsTowardOvr(pos, target, { name, jitter: opts.jitter });
}
